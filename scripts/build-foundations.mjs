import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const tokens = JSON.parse(await readFile(path.join(root, 'packages/tokens/src/tokens.json'), 'utf8'))
const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'))
const checkOnly = process.argv.includes('--check')
const escape = value => String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;')
const kebab = value => value.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()
const label = value => value.replace(/([a-z])([A-Z])/g, '$1 $2').replace(/^./, letter => letter.toUpperCase())
const copy = (value, name) => `<button class="as-button" data-variant="secondary" type="button" data-copy="${escape(value)}" aria-label="Copy ${escape(name)}">Copy</button>`
const themes = Object.keys(tokens.themes)
const html = `<!DOCTYPE html>
<!-- Generated by scripts/build-foundations.mjs. Do not edit directly. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>ASIG foundations and tokens</title>
  <link rel="stylesheet" href="../packages/tokens/dist/tokens.css">
  <link rel="stylesheet" href="../packages/ui-patterns/all.css">
  <link rel="stylesheet" href="./assets/catalog.css">
  <link rel="stylesheet" href="./assets/guide.css">
  <script src="./assets/foundations.js" defer></script>
</head>
<body data-as-theme="operations" class="guide-page">
  <a class="as-skip-link" href="#content">Skip to foundations</a>
  <main id="content" class="guide-shell" tabindex="-1">
    <nav aria-label="Design resources"><a href="./index.html">Component catalogue</a><a href="../examples/operations.html">Operations example</a><a href="../site/document.html?file=DESIGN.md">Design brief</a></nav>
    <header class="guide-header">
      <p class="catalog-kicker">ASIG ${escape(pkg.version)} · Foundations</p>
      <h1 class="as-text" data-role="title">A shared visual language</h1>
      <p>Choose a theme, inspect its semantic roles, and copy the variables into your existing components.</p>
      <div class="guide-toolbar">
        <div class="as-field"><label class="as-field__label" for="theme-select">Product theme</label><select class="as-select" id="theme-select">${themes.map(theme => `<option value="${theme}">${label(theme.replaceAll('-', ' '))}</option>`).join('')}</select></div>
        <div class="as-field"><label class="as-field__label" for="token-search">Find a color token</label><input class="as-control" type="search" id="token-search" placeholder="Try surface, focus or danger"></div>
      </div>
      <p id="copy-status" role="status" aria-live="polite">Copy a variable to keep your implementation connected to ASIG.</p>
    </header>
    <section aria-labelledby="colors-title">
      <h2 id="colors-title" class="as-text" data-role="section">Semantic colors</h2>
      <p>Roles describe intent. Border is decorative; border strong defines controls. Pair status with text, never color alone.</p>
      <p id="color-count" role="status"></p>
      ${themes.map(theme => `<div class="token-grid" data-token-theme="${theme}"${theme === 'operations' ? '' : ' hidden'}>
        ${Object.entries(tokens.themes[theme]).map(([role, value]) => {
          const variable = `--as-color-${kebab(role)}`
          return `<article class="token-card" data-token-name="${escape(`${label(role)} ${variable}`)}">
            <div class="token-sample" style="background: var(${variable})" aria-hidden="true"></div>
            <h3>${label(role)}</h3><code>${variable}</code><p>${value}</p>
            ${copy(`var(${variable})`, variable)}
          </article>`
        }).join('\n')}
      </div>`).join('\n')}
      <p id="token-empty" hidden>No matching tokens. Clear the search to see the full palette.</p>
    </section>
    <section aria-labelledby="type-title">
      <h2 id="type-title" class="as-text" data-role="section">Typography by purpose</h2>
      <p>Inherit the product font. Choose heading levels by structure; choose roles by hierarchy. <a href="../site/document.html?file=docs/TYPOGRAPHY.md">Typography guidance</a></p>
      <div class="type-list">${Object.entries(tokens.foundation.type).map(([role, values]) => `<article class="type-row">
        <div><h3>${label(role)}</h3><code>${escape(values.size)}</code></div>
        <p class="as-text" data-role="${role}">${role === 'numeric' ? '$12,480.00' : role === 'title' ? 'Vendor procurement' : role === 'section' ? 'Receiving details' : role === 'label' ? 'Receiving location' : role === 'caption' ? 'Required when placing the vendor order.' : 'Keep the next action and its context together.'}</p>
        ${copy(`<${role === 'title' ? 'h1' : 'p'} class="as-text" data-role="${role}">Your text</${role === 'title' ? 'h1' : 'p'}>`, `${role} markup`)}
      </article>`).join('\n')}</div>
    </section>
    <section aria-labelledby="space-title">
      <h2 id="space-title" class="as-text" data-role="section">Spacing and shape</h2>
      <p>Use small gaps within a field and larger gaps between tasks. Let controls grow with their labels.</p>
      <div class="token-grid">${Object.entries(tokens.foundation.space).map(([key, value]) => `<article class="token-card"><h3>Space ${key}</h3><div class="space-sample" style="width: var(--as-space-${key})" aria-hidden="true"></div><code>--as-space-${key}</code><p>${value}</p>${copy(`var(--as-space-${key})`, `space ${key}`)}</article>`).join('\n')}
      ${Object.entries(tokens.foundation.radius).map(([key, value]) => `<article class="token-card"><h3>${label(key)} radius</h3><div class="shape-sample" style="border-radius: var(--as-radius-${key})" aria-hidden="true"></div><code>--as-radius-${key}</code><p>${value}</p>${copy(`var(--as-radius-${key})`, `${key} radius`)}</article>`).join('\n')}</div>
    </section>
    <section aria-labelledby="depth-title">
      <h2 id="depth-title" class="as-text" data-role="section">Depth with a purpose</h2>
      <p>Reserve higher elevation for floating content. Dense tables and financial review stay calm and opaque.</p>
      <div class="token-grid">${Object.keys(tokens.foundation.elevation).map(key => `<article class="token-card"><div class="shape-sample" style="box-shadow: var(--as-elevation-${key})" aria-hidden="true"></div><h3>${label(key)}</h3><code>--as-elevation-${key}</code>${copy(`var(--as-elevation-${key})`, `${key} elevation`)}</article>`).join('\n')}</div>
    </section>
    <footer>Generated from versioned token JSON. ASIG ${escape(pkg.version)}; product adoption is separate.</footer>
  </main>
</body>
</html>
`

async function emit(relative, output) {
  const file = path.join(root, relative)
  if (checkOnly) {
    if (await readFile(file, 'utf8').catch(() => '') !== output) throw new Error(`${relative} is stale. Run npm run build.`)
  } else await writeFile(file, output)
}
await emit('site/foundations.html', html)
const index = await readFile(path.join(root, 'site/index.html'), 'utf8')
if (!/<!-- asig-version -->.*?<!-- \/asig-version -->/.test(index)) throw new Error('Catalogue version marker missing')
await emit('site/index.html', index.replace(/<!-- asig-version -->.*?<!-- \/asig-version -->/, `<!-- asig-version -->${pkg.version}<!-- /asig-version -->`))
console.log(`${checkOnly ? 'Verified' : 'Built'} foundations gallery and catalogue version from source.`)
